package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strconv"
)

type toolSchema struct {
	name     string
	variable string
}

func main() {
	toolSchemas, err := loadToolSchemas("server/server.go")
	if err != nil {
		panic(err)
	}

	if err := writeToolSchemas("types/flowlines_tool_schemas.generated.go", toolSchemas); err != nil {
		panic(err)
	}
}

func loadToolSchemas(filename string) ([]toolSchema, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("cannot parse generated MCP server: %w", err)
	}

	toolSchemas := make([]toolSchema, 0)
	ast.Inspect(
		file,
		func(node ast.Node) bool {
			call, ok := node.(*ast.CallExpr)
			if !ok || len(call.Args) < 2 || !isAddToolCall(call.Fun) {
				return true
			}

			tool, ok := call.Args[1].(*ast.UnaryExpr)
			if !ok {
				return true
			}

			literal, ok := tool.X.(*ast.CompositeLit)
			if !ok {
				return true
			}

			name, schema := toolFields(literal)
			if name != "" && schema != "" {
				toolSchemas = append(toolSchemas, toolSchema{name: name, variable: schema})
			}

			return true
		},
	)

	if len(toolSchemas) == 0 {
		return nil, fmt.Errorf("generated MCP server contains no typed tools")
	}

	sort.Slice(toolSchemas, func(i, j int) bool { return toolSchemas[i].name < toolSchemas[j].name })

	return toolSchemas, nil
}

func isAddToolCall(expr ast.Expr) bool {
	selector, ok := expr.(*ast.SelectorExpr)
	return ok && selector.Sel.Name == "AddTool"
}

func toolFields(literal *ast.CompositeLit) (string, string) {
	var name, schema string
	for _, element := range literal.Elts {
		field, ok := element.(*ast.KeyValueExpr)
		if !ok {
			continue
		}

		key, ok := field.Key.(*ast.Ident)
		if !ok {
			continue
		}

		switch key.Name {
		case "Name":
			value, ok := field.Value.(*ast.BasicLit)
			if !ok || value.Kind != token.STRING {
				continue
			}

			name, _ = strconv.Unquote(value.Value)
		case "InputSchema":
			value, ok := field.Value.(*ast.SelectorExpr)
			if ok {
				schema = value.Sel.Name
			}
		}
	}

	return name, schema
}

